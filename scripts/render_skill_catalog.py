#!/usr/bin/env python3
"""Render the router's compact child-skill catalog from skills-manifest.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path, PurePosixPath
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "skills-manifest.json"
CATALOG_PATH = ROOT / "amazon-skill-router" / "references" / "skill-catalog.md"
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def within(root: Path, relative: str) -> Path:
    path = (root / relative).resolve()
    if path != root.resolve() and root.resolve() not in path.parents:
        raise ValueError(f"Path escapes repository: {relative}")
    return path


def load_manifest() -> dict:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    if manifest.get("schema_version") != 2 or manifest.get("platform") != "amazon":
        raise ValueError("Expected Amazon skill manifest schema_version 2")
    router = manifest.get("router")
    if not isinstance(router, dict) or router.get("name") != "amazon-skill-router":
        raise ValueError("Manifest must define amazon-skill-router")
    if not isinstance(manifest.get("routing_policy"), list) or not manifest["routing_policy"]:
        raise ValueError("Manifest must define routing_policy")
    router_root = within(ROOT, router["path"])
    if not router_root.is_dir():
        raise ValueError(f"Missing router directory: {router['path']}")
    for relative in router.get("include", []):
        source = within(router_root, relative)
        if source != router_root and router_root not in source.parents:
            raise ValueError(f"Router include escapes router directory: {relative}")
        if not source.exists():
            raise ValueError(f"Missing router include: {router['path']}/{relative}")
    skills = manifest.get("skills")
    if not isinstance(skills, list) or not skills:
        raise ValueError("Manifest must contain at least one child skill")

    seen = set()
    for skill in skills:
        name = skill.get("name", "")
        if not NAME_RE.fullmatch(name) or name == router["name"]:
            raise ValueError(f"Invalid child skill name: {name}")
        if name in seen:
            raise ValueError(f"Duplicate child skill name: {name}")
        seen.add(name)
        if not skill.get("category") or not skill.get("description") or not skill.get("triggers"):
            raise ValueError(f"Missing routing metadata for {name}")
        skill_root = within(ROOT, skill["path"])
        if not str(PurePosixPath(skill["path"])).startswith("skills/"):
            raise ValueError(f"Child skill must be stored under skills/: {skill['path']}")
        if not skill_root.is_dir():
            raise ValueError(f"Missing skill directory: {skill['path']}")
        for relative in skill.get("include", []):
            source = within(skill_root, relative)
            if source != skill_root and skill_root not in source.parents:
                raise ValueError(f"Skill include escapes skill directory: {relative}")
            if not source.exists():
                raise ValueError(f"Missing skill include: {skill['path']}/{relative}")
        skill_file = skill_root / "SKILL.md"
        text = skill_file.read_text(encoding="utf-8")
        frontmatter_name = re.search(r"(?m)^name:\s*(\S+)\s*$", text)
        if not frontmatter_name or frontmatter_name.group(1) != name:
            raise ValueError(f"SKILL.md name does not match manifest entry: {name}")
    return manifest


def render_catalog(manifest: dict) -> str:
    lines = [
        "# Amazon Skill Catalog",
        "",
        "Generated from `skills-manifest.json`. Do not edit this file by hand.",
        "",
        "## Routing policy",
        "",
    ]
    lines.extend(f"- {rule}" for rule in manifest.get("routing_policy", []))
    lines.extend(["", "## Child skills", ""])
    for skill in manifest["skills"]:
        lines.extend([
            f"### {skill['name']}",
            "",
            f"- **Category:** {skill['category']}",
            f"- **Repository path:** `{skill['path']}/`",
            f"- **Use for:** {skill['description']}",
            f"- **Triggers:** {'; '.join(skill['triggers'])}",
        ])
        excludes = skill.get("excludes", [])
        if excludes:
            lines.append(f"- **Exclude:** {'; '.join(excludes)}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the generated catalog")
    mode.add_argument("--check", action="store_true", help="fail if the catalog is out of date")
    args = parser.parse_args()

    try:
        manifest = load_manifest()
        rendered = render_catalog(manifest)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"Invalid skill manifest: {exc}", file=sys.stderr)
        return 1

    if args.write:
        CATALOG_PATH.parent.mkdir(parents=True, exist_ok=True)
        CATALOG_PATH.write_text(rendered, encoding="utf-8")
        print(f"Updated {CATALOG_PATH.relative_to(ROOT)}")
        return 0

    current = CATALOG_PATH.read_text(encoding="utf-8") if CATALOG_PATH.exists() else ""
    if current != rendered:
        print("Skill catalog is out of date; run python scripts/render_skill_catalog.py --write", file=sys.stderr)
        return 1
    print("Skill catalog matches skills-manifest.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
